const fs = require('fs');
const path = require('path');

const core = require('./AYHEM_AI_CORE_AUTO4.js');
const memory = require('./ayhem-memory.js');

const ROOT = __dirname;
const BACKUP_DIR = path.join(ROOT, 'full_backups');

if (!fs.existsSync(BACKUP_DIR)) fs.mkdirSync(BACKUP_DIR);

// تقييم المخاطر
function riskAssessment(recommendation) {
    if (!recommendation) return 0;

    let risk = 0;

    if (recommendation.includes('delete')) risk += 0.7;
    if (recommendation.includes('rewrite')) risk += 0.5;
    if (recommendation.includes('optimize')) risk += 0.2;

    return Math.min(risk, 1);
}

// تقييم الثقة
function confidenceScore(analysis) {
    return analysis?.relevanceScore || 0.5;
}

// نسخ احتياطي ذكي
function backup(filePath) {
    const fileName = path.basename(filePath);
    const backupPath = path.join(BACKUP_DIR, `${fileName}_${Date.now()}.bak`);
    fs.copyFileSync(filePath, backupPath);
}

// إنشاء ملف جديد
function createNewModule(name, content) {
    const filePath = path.join(ROOT, name);
    fs.writeFileSync(filePath, content, 'utf-8');
    console.log(`🧠 تم إنشاء وحدة جديدة: ${name}`);
}

// تعديل ذكي
function applyChange(filePath, recommendation) {
    backup(filePath);

    let content = fs.readFileSync(filePath, 'utf-8');

    // تحسين ذكي (مثال)
    content += `\n// EVOLUTION UPDATE: ${recommendation}\n`;

    fs.writeFileSync(filePath, content, 'utf-8');
}

// المحرك الذاتي الكامل
async function fullEvolutionCycle() {
    const files = fs.readdirSync(ROOT);

    for (const file of files) {
        const filePath = path.join(ROOT, file);

        if (!fs.statSync(filePath).isFile()) continue;

        const content = fs.readFileSync(filePath, 'utf-8');

        try {
            const analysis = await core.deepAnalyze(file, content);
            const recommendation = await core.generateRecommendation(file, content);

            const risk = riskAssessment(recommendation);
            const confidence = confidenceScore(analysis);

            // قرار التنفيذ
            if (confidence > 0.6 && risk < 0.8) {
                applyChange(filePath, recommendation);
            }

            // إنشاء وحدات جديدة عند الحاجة
            if (confidence > 0.8 && recommendation.includes('create module')) {
                createNewModule(
                    `auto_module_${Date.now()}.js`,
                    `// Generated by AYHEM AI\nconsole.log("Auto Module Active");`
                );
            }

            // تخزين الذاكرة
            memory.storeAIInsight(file, {
                analysis,
                recommendation,
                risk,
                confidence,
                time: new Date().toISOString()
            });

        } catch (e) {
            console.error(`خطأ تطوري: ${file}`, e.message);
        }
    }

    console.log('🚀 Full Evolution Cycle Completed');
}

// تشغيل مستمر
setInterval(fullEvolutionCycle, 60 * 1000);

console.log('🔥 FULL AUTONOMOUS EVOLUTION ACTIVATED');
